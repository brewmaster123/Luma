#!/usr/bin/env python3
"""Writes Sources/iPhone/NightSkyData.swift from scripts/sky-data.json.

sky-data.json was exported from the approved design mock-up (Atelier-Night-Prototype-06):
the stars of the Night screen with their visibility behind the painted clouds and beside
the swinging moon, the schedule of shooting stars and comets, and the stars of the Settings sky.
The app draws exactly these, so its sky matches the mock-up. Not run by CI.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "scripts/sky-data.json").read_text(encoding="utf-8"))


def num(value):
    text = repr(round(float(value), 4))
    return text if ("." in text or "e" in text) else text + ".0"


def rows(items):
    return ",\n".join("    [" + ", ".join(num(v) for v in row) + "]" for row in items)


soft_rows = []
star_rows = []
for star in data["stars"]:
    index = -1
    if not star["far"]:
        index = len(soft_rows)
        soft_rows.append(star["soft"])
    star_rows.append([star["x"], star["y"], star["r"], star["a"], star["period"], star["offset"],
                      star["tint"], star["c"], index])
micro_rows = [[m["x"], m["y"], m["c"]] + m["seen"] for m in data["micro"]]
meteor_rows = [[m["at"], m["ax"], m["ay"], m["bx"], m["by"], m["tail"], m["dur"], m["alpha"], m["w"]]
               for m in data["meteors"]]
comet_rows = [[c["at"], c["ax"], c["ay"], c["bx"], c["by"], c["tail"], c["dur"]] for c in data["comets"]]
settings_rows = [[s["x"], s["y"], s["r"], s["a"], s["period"], s["offset"], s["tint"], s["spark"]]
                 for s in data["skyStars"]]

text = f"""// Generated by scripts/generate_sky_data.py from scripts/sky-data.json. Do not edit by hand.
// The numbers come from the approved design mock-up, so the app's sky is the mock-up's sky.
import Foundation

enum NightSkyData {{
  /// Swing angles (degrees) at which `softness` and the micro-star visibility were sampled.
  static let angles: [Double] = [{", ".join(num(a) for a in data["angles"])}]

  /// Night screen stars, in the painting's coordinates (1024 x 1536):
  /// x, y, radius, alpha, twinkle period, twinkle offset, tint index, clearness (0 = behind a painted cloud),
  /// row of `softness` for a star close to the moon, or -1 for a star that the moon never reaches.
  static let stars: [[Double]] = [
{rows(star_rows)}
  ]

  /// How visible a star close to the moon is at each of `angles` (0 = hidden by the moon or its glow).
  static let softness: [[Double]] = [
{rows(soft_rows)}
  ]

  /// The eight faint points inside the crescent's opening: x, y, clearness, then visibility at each of `angles`.
  static let microStars: [[Double]] = [
{rows(micro_rows)}
  ]

  /// Shooting stars: start time (s), from x, y, to x, y, tail length, duration, alpha, width.
  /// Every path was checked in the mock-up to stay clear of the moon, its opening and the painted clouds.
  static let meteors: [[Double]] = [
{rows(meteor_rows)}
  ]

  /// Comets: start time (s), from x, y, to x, y, tail length, duration.
  static let comets: [[Double]] = [
{rows(comet_rows)}
  ]

  /// Settings sky, in screen points of the 402 x 874 design:
  /// x, y, radius, alpha, twinkle period, twinkle offset, tint index, 1 for a star that sparkles.
  static let settingsStars: [[Double]] = [
{rows(settings_rows)}
  ]
}}
"""
target = ROOT / "Sources/iPhone/NightSkyData.swift"
target.write_text(text, encoding="utf-8", newline="\n")
print(f"{target.name}: {len(star_rows)} stars, {len(soft_rows)} near the moon, {len(micro_rows)} micro, "
      f"{len(meteor_rows)} meteors, {len(comet_rows)} comets, {len(settings_rows)} settings stars")
